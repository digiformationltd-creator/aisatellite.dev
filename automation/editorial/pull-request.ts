import type { ArticleDraft } from '../shared/types.js';

export class PullRequestReviewHelper {
  /**
   * Generates a GitHub Pull Request template for human editorial review
   */
  static generatePrBody(draft: ArticleDraft): string {
    const claims = draft.evidenceLedger
      .map((c) => `- **Claim:** ${c.claim}\n  - Source: [${c.sourceUrl}](${c.sourceUrl}) (Confidence: ${c.confidence})`)
      .join('\n');

    return `## 🛰️ AI Satellite Editorial Draft Review

### Article Summary
- **Title:** ${draft.title}
- **Category:** ${draft.category}
- **Slug:** \`/playbooks/${draft.slug}\`
- **Partner Context:** \`${draft.partnerContext}\`
- **Reading Time:** ${draft.readingTime}

---

### 🛡️ Grounded Evidence Ledger
The factual claims in this article have been anchored to the following official documentation sources:
${claims}

---

### 📋 Editorial Compliance Checklist
- [ ] No ungrounded or exaggerated technical claims
- [ ] Code snippets verified safe for production execution
- [ ] Commercial partnership disclosures verified and compliant
- [ ] Links verified live and canonical
- [ ] Markdown formatting, tables, and headings adhere to style guidelines

---

*Generated by AI Satellite Autonomous Publishing Engine v2.0*
`;
  }
}
